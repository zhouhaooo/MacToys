import AppKit
import ImageIO
import UniformTypeIdentifiers

/// 定时检查剪贴板有没有变化，有新内容就记下来。
///
/// macOS 没有剪贴板变化的通知，只能定时比较 changeCount。只在主线程上使用。
final class ClipboardWatcher {
    private let pasteboard = NSPasteboard.general
    private let store: ClipboardStore
    private let config: () -> ClipboardConfig
    private var timer: Timer?
    private var lastChangeCount: Int
    /// 本程序自己写进剪贴板时的计数，看到它就不再记录。
    private var ownChangeCount: Int?
    private let captureQueue = DispatchQueue(label: "MacToys.ClipboardCapture", qos: .utility, autoreleaseFrequency: .workItem)
    private var cancellation = WorkCancellation()
    private let prepared = Locked<[(ClipboardCapture, Date, WorkCancellation, Int)]>([])
    private let pendingBytes = Locked(0)

    struct Snapshot {
        let text: String?
        let extras: [String: Data]
        let image: Data?
        let isPNG: Bool
        let sourceApp: String?
    }

    deinit { timer?.invalidate() }

    /// 密码管理器等用这些类型标记“不要记录”（nspasteboard.org 的约定）。
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// 只记录这么大以内的内容，太大的跳过。
    static let maxTextBytes = 2 * 1024 * 1024
    static let maxImageBytes = 30 * 1024 * 1024
    static let maxExtraBytes = 2 * 1024 * 1024
    /// TIFF 转 PNG 前限制解码像素；PNG 直接保留编码数据，不展开像素。
    static let maxDecodedImagePixels = 30_000_000

    init(store: ClipboardStore, config: @escaping () -> ClipboardConfig) {
        self.store = store
        self.config = config
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        cancellation = WorkCancellation()
        lastChangeCount = pasteboard.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        cancellation.cancel()
        discardPrepared()
        timer?.invalidate()
        timer = nil
    }

    /// 本程序写完剪贴板后调用，避免把自己写的内容又记一遍。
    func noteOwnWrite() {
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == ownChangeCount { return }

        let cfg = config()
        // 没有“始终允许”读取剪贴板时不读，否则每次复制都会弹出系统询问。
        guard cfg.enabled, PasteboardAccess.status == .allowed else { return }
        guard let snapshot = Self.snapshot(from: pasteboard, recordImages: cfg.recordImages) else { return }
        let bytes = (snapshot.text?.utf8.count ?? 0) + (snapshot.image?.count ?? 0)
            + snapshot.extras.values.reduce(0) { $0 + $1.count }
        guard pendingBytes.update({ value in
            guard value + bytes <= 64 << 20 else { return false }
            value += bytes
            return true
        }) else { return }
        let token = cancellation
        let copiedAt = Date()
        captureQueue.async { [weak self] in
            guard let self else { return }
            guard !token.isCancelled, let capture = Self.prepare(snapshot), !token.isCancelled else {
                self.pendingBytes.update { $0 -= bytes }
                return
            }
            self.prepared.update { $0.append((capture, copiedAt, token, bytes)) }
            DispatchQueue.main.async { [weak self] in self?.deliverPrepared() }
        }
    }

    private func deliverPrepared() {
        let captures = prepared.update { value -> [(ClipboardCapture, Date, WorkCancellation, Int)] in
            defer { value = [] }
            return value
        }
        for (capture, date, token, bytes) in captures {
            pendingBytes.update { $0 -= bytes }
            guard !token.isCancelled else { continue }
            store.addInBackground(capture, maxItems: config().maxItems, now: date)
        }
    }

    private func discardPrepared() {
        let bytes = prepared.update { value -> Int in
            defer { value = [] }
            return value.reduce(0) { $0 + $1.3 }
        }
        pendingBytes.update { $0 -= bytes }
    }

    /// 退出时先收下已观察到的复制，再让 store 完成顺序写盘。
    func flush() {
        timer?.invalidate()
        timer = nil
        captureQueue.sync {}
        deliverPrepared()
    }

    #if DEBUG || SELF_TEST
    static func capture(from pasteboard: NSPasteboard, recordImages: Bool) -> ClipboardCapture? {
        snapshot(from: pasteboard, recordImages: recordImages).flatMap(prepare)
    }
    #endif

    /// 系统剪贴板只在主线程读取；解码与散列不在此处执行。
    static func snapshot(from pasteboard: NSPasteboard, recordImages: Bool) -> Snapshot? {
        guard let item = pasteboard.pasteboardItems?.first else { return nil }
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        if !types.isDisjoint(with: ignoredTypes) { return nil }
        // 跳过 Finder 复制的文件，只记录文字和图片。
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) { return nil }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if let text = item.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= maxTextBytes else { return nil }
            var extras: [String: Data] = [:]
            for type in [NSPasteboard.PasteboardType.rtf, .html] {
                if let data = item.data(forType: type), data.count <= maxExtraBytes {
                    extras[type.rawValue] = data
                }
            }
            return Snapshot(text: text, extras: extras, image: nil, isPNG: false, sourceApp: source)
        }
        guard recordImages else { return nil }
        let png = item.data(forType: .png)
        guard let raw = png ?? item.data(forType: .tiff), raw.count <= maxImageBytes else { return nil }
        return Snapshot(text: nil, extras: [:], image: raw, isPNG: png != nil, sourceApp: source)
    }

    static func prepare(_ snapshot: Snapshot) -> ClipboardCapture? {
        if let text = snapshot.text {
            return ClipboardCapture(kind: .text, text: text, extras: snapshot.extras,
                                    fingerprint: ClipboardStore.fingerprint([Data("text".utf8), Data(text.utf8)]),
                                    sourceApp: snapshot.sourceApp)
        }
        guard let raw = snapshot.image, raw.count <= maxImageBytes,
              let source = CGImageSourceCreateWithData(raw as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int, width > 0, height > 0 else { return nil }
        let png: Data
        if snapshot.isPNG {
            guard CGImageSourceGetType(source) as String? == UTType.png.identifier else { return nil }
            png = raw
        } else {
            guard width <= maxDecodedImagePixels / height,
                  let rep = NSBitmapImageRep(data: raw),
                  let converted = rep.representation(using: .png, properties: [:]), converted.count <= maxImageBytes else { return nil }
            png = converted
        }
        return ClipboardCapture(kind: .image, text: nil, png: png,
                                imageSize: CGSize(width: width, height: height),
                                fingerprint: ClipboardStore.fingerprint([Data("image".utf8), png]), sourceApp: snapshot.sourceApp)
    }
}
